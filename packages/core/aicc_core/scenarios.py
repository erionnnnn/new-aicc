_NORM = re.compile(r"[\s.,!?~…·'\"-]+")


def normalize(text: str) -> str:
    return _NORM.sub("", text.lower())


def match(text: str, kinds: tuple[str, ...] = ("PREF", "END", "INFO")) -> Scenario | None:
    t = normalize(text)
    if not t:
        return None
    for s in SCENARIOS:
        if s.kind in kinds and any(re.search(k, t) for k in s.keywords):
            return s
    return None


