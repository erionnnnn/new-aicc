_NORM = re.compile(r"[\s.,!?~…·'\"-]+")


def normalize(text: str) -> str:
    return _NORM.sub("", text.lower())


def match(text: str, kinds: tuple[str, ...] = ("DELETE", "REVIEW", "PREF", "END", "INFO")) -> Scenario | None:
    t = normalize(text)
    if not t:
        return None
    for s in SCENARIOS:
        if s.kind in kinds and any(_pat(k).search(t) for k in s.keywords):
            return s
    return None


_PATS: dict[str, re.Pattern] = {}


def _pat(k: str) -> re.Pattern:
    p = _PATS.get(k)
    if p is None:
        p = _PATS[k] = re.compile(k)
    return p


